def test_the_failure_names_every_moved_label_and_what_it_costs() -> None:
    """Parsed out of the message, never `"seed" in message`.

    A substring that appears anyway is this project's most repeated test defect
    — five occurrences now — and a failure message is exactly the kind of text
    in which any given word appears somewhere.
    """
    golden = ["a.model_id 1111", "b.model_id 2222", "c.points 27"]
    current = ["a.model_id 9999", "b.model_id 2222", "c.points 28"]

    message = report(golden, current)

    moved = dict(
        (match.group(1), (match.group(2), match.group(3)))
        for match in re.finditer(r"^  moved (\S+): (\S+) → (\S+)$", message, re.M)
    )
    assert moved == {"a.model_id": ("1111", "9999"), "c.points": ("27", "28")}
    assert ORPHAN_WARNING in message
    assert REBASELINE in message


def test_the_failure_names_a_label_that_disappeared() -> None:
    """A probe line deleted is a hole in the gate, and reads as no change at all
    unless the message says otherwise."""
    message = report(["a.model_id 1111", "b.model_id 2222"], ["a.model_id 1111"])

    assert re.findall(r"^  gone (\S+)$", message, re.M) == ["b.model_id"]


def test_an_unchanged_surface_reports_nothing() -> None:
    """The report is capable of saying nothing, which is what makes the
    assertions above statements about a real mismatch."""
    assert report(["a 1", "b 2"], ["a 1", "b 2"]) == ""


def test_a_missing_golden_asks_for_a_deliberate_rebaseline(tmp_path: Path) -> None:
    with pytest.raises(AssertionError) as failure:
        read_golden(tmp_path / "identity_surface.txt")

    assert REBASELINE in str(failure.value)


def test_this_module_cannot_write_the_golden() -> None:
    """Statically, in the style `test_boundaries.py` already uses.

    A convenience flag added later — `--update-golden`, an environment variable,
    a `write_text` in a fixture — fails this test rather than silently disarming
    the gate.
    """
    tree = ast.parse(Path(__file__).read_text(encoding="utf-8"))
    writes = [
        node
        for node in ast.walk(tree)
        if isinstance(node, ast.Call)
        and (
            (isinstance(node.func, ast.Name) and node.func.id == "open")
            or (
                isinstance(node.func, ast.Attribute)
                and node.func.attr
                in {"open", "write", "write_text", "write_bytes", "writelines"}
            )
        )
    ]
    assert not writes, (
        "this module can write; the golden must only ever be re-baselined by "
        f"hand:\n    {REBASELINE}"
    )


