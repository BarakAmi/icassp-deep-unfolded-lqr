def _class_definitions(tree: ast.AST, prefix: str = "") -> list[str]:
    """Qualified names of every class in `tree` that DEFINES `get_signature`."""
    found: list[str] = []
    for node in ast.iter_child_nodes(tree):
        if not isinstance(node, ast.ClassDef):
            continue
        qualname = f"{prefix}{node.name}"
        if any(
            isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef))
            and child.name == "get_signature"
            for child in node.body
        ):
            found.append(qualname)
        found.extend(_class_definitions(node, f"{qualname}."))
    return found


def discover_signables() -> dict[str, str]:
    """`path::QualName` -> importable module name, for every signable class.

    **The filesystem, never `pkgutil`.** A discovery that walks imported
    packages sees what the interpreter happened to import, which on a partially
    imported tree is a subset that shrinks silently — and a coverage test whose
    denominator can shrink is a coverage test that can be satisfied by breaking
    an import.
    """
    discovered: dict[str, str] = {}
    for path in sorted(SRC.rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        relative = path.relative_to(SRC)
        parts = [part for part in relative.with_suffix("").parts if part != "__init__"]
        module = ".".join(["mbl", *parts])
        for qualname in _class_definitions(tree):
            discovered[f"{relative.as_posix()}::{qualname}"] = module
    return discovered


def _resolve(module_name: str, qualname: str) -> Any:
    obj: Any = importlib.import_module(module_name)
    for part in qualname.split("."):
        obj = getattr(obj, part)
    return obj


@contextmanager
def recording() -> Iterator[set[str]]:
    """Wrap `get_signature` on every discovered class and record what is called.

    The covered set is **derived, never carried**: two hand-maintained lists
    would drift against each other and against the probe, and the drift would
    read as coverage.

    A patched `get_signature` left on a live class leaks into every test that
    runs after this one in the same session, so the restore is in `finally` and
    `test_the_recorder_leaves_every_class_as_it_found_it` checks it *after* the
    block has exited — which is the only place the check means anything.
    """
    seen: set[str] = set()
    restore: list[tuple[Any, Any]] = []
    for key, module_name in discover_signables().items():
        owner = _resolve(module_name, key.split("::", 1)[1])
        original = owner.__dict__.get("get_signature")
        if not inspect.isfunction(original):  # inherited, or not a plain method
            continue

        def recorder(
            self: Any, *args: Any, _key: str = key, _original: Any = original, **kw: Any
        ) -> Any:
            seen.add(_key)
            return _original(self, *args, **kw)

        setattr(owner, "get_signature", recorder)
        restore.append((owner, original))
    try:
        yield seen
    finally:
        for owner, original in restore:
            setattr(owner, "get_signature", original)


@pytest.fixture
def reached(probe: ModuleType) -> Iterator[set[str]]:
    """Which signable classes one call of the probe actually exercises."""
    with recording() as seen:
        probe.surface_lines()
        yield seen


def test_every_signable_class_is_accounted_for(reached: set[str]) -> None:
    """Either the probe reaches it, or `NOT_IN_THE_GATE` says why it need not.

    This is the mechanism that needs no enumeration of today's families: a new
    signable class fails here until someone decides which side of the gate it is
    on. It is the standing rule against designing around a free parameter's
    current value, applied to the gate itself.
    """
    unaccounted = set(discover_signables()) - reached - set(NOT_IN_THE_GATE)
    assert not unaccounted, (
        "these classes define `get_signature`, are not reached by the identity "
        "probe, and are not excluded from it:\n  "
        + "\n  ".join(sorted(unaccounted))
        + "\n\nDecide which they are: add a probe line if the class can reach a "
        "stored identifier, or an entry in NOT_IN_THE_GATE with the reason it "
        "cannot."
    )


def test_no_exclusion_outlives_its_class() -> None:
    """An exclusion for a class that no longer exists is a comment pretending to
    be a decision, and it hides the day the class comes back under a new name."""
    stale = set(NOT_IN_THE_GATE) - set(discover_signables())
    assert not stale, (
        "NOT_IN_THE_GATE names classes that no longer define `get_signature`:\n  "
        + "\n  ".join(sorted(stale))
    )


def test_every_exclusion_carries_a_reason() -> None:
    reasonless = [key for key, reason in NOT_IN_THE_GATE.items() if len(reason) < 40]
    assert not reasonless, (
        "an exclusion without a reason is an exclusion nobody can review:\n  "
        + "\n  ".join(sorted(reasonless))
    )


def test_the_recorder_leaves_every_class_as_it_found_it(probe: ModuleType) -> None:
    """The companion assertion to `recording`'s `finally`, taken **after** the
    block exits — inside it, the recorder is supposed to be installed.

    Checked on a class the probe genuinely reaches and against the original
    function object, not against its name: a wrapper that copied `__name__`
    through `functools.wraps` would pass a name comparison while still being
    the wrapper.
    """
    problem_spec = _resolve("mbl.spec.problem", "ProblemSpec")
    before = problem_spec.__dict__["get_signature"]

    with recording() as seen:
        probe.surface_lines()
        assert problem_spec.__dict__["get_signature"] is not before, (
            "the recorder never wrapped a class the probe reaches, so this "
            "test would pass without restoring anything"
        )

    assert seen, "the recorder must have recorded something to be meaningful"
    assert problem_spec.__dict__["get_signature"] is before
