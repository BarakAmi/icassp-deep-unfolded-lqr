"""The identity gate — Stage 7 Phase A.

§7.5 of the parent architecture closes with *"a signature-stability test asserts
that no `ProblemID`/`ModelID` changes as a result of the refactor (a silent
identity change would orphan the entire store)"*. **There was no such test.**
Every identifier assertion in the suite is either an arbitrary literal
(`ModelID("0123456789abcdef")` — 50 of them across 8 files) or a self-comparison
(`a.problem_id == b.problem_id`), and both are invariant under a *uniform* shift:
a refactor that moved every signature tree identically would orphan all 162
stored models and pass green.

The only thing that could see such a shift was `tools/probes/identity_probe.py`,
a cross-branch diff run by hand, outside `pytest`, that a merge can forget. This
module is that probe made unforgettable: the surface is frozen as a committed
golden and compared on every run.

**The golden is never regenerated by the test.** A golden that rewrites itself on
failure is a test that cannot fail — the same defect class the paragraph above
describes, one level up. Re-baselining is a deliberate manual command with no
flag and no environment variable, and `test_this_module_cannot_write_the_golden`
asserts statically that no path through this file can perform it.
"""

