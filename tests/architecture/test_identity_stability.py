def _load_probe() -> ModuleType:
    """Import the probe by path. `tools/` is not a package, deliberately: it is
    run as a script against two worktrees at once."""
    spec = importlib.util.spec_from_file_location("identity_probe", PROBE)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def probe() -> ModuleType:
    return _load_probe()


@pytest.fixture(scope="module")
def surface(probe: ModuleType) -> list[str]:
    return list(probe.surface_lines())


def read_golden(path: Path = GOLDEN) -> list[str]:
    """The committed surface.

    A missing fixture is a *decision that was not taken*, not an I/O error, so
    it says what to do about it. `FileNotFoundError` from a test whose subject
    is a golden file tells the reader nothing they did not already see.
    """
    if not path.is_file():
        raise AssertionError(
            f"the identity golden is missing at {path}. It is committed, never "
            f"generated by the suite; create it deliberately with:\n    {REBASELINE}"
        )
    return path.read_text(encoding="utf-8").splitlines()


def _labelled(lines: Sequence[str]) -> dict[str, str]:
    """`label value` -> `{label: value}`, in order."""
    labelled: dict[str, str] = {}
    for text in lines:
        label, _, value = text.partition(" ")
        labelled[label] = value
    return labelled


def report(golden: Sequence[str], current: Sequence[str]) -> str:
    """What moved, or `""` when nothing did.

    A bare `assert a == b` over 73 lines is unreadable at the moment it matters
    most — pytest prints two walls of hexadecimal and the reader has to find the
    changed one. This names each moved label, and says what a moved label costs.
    """
    if list(golden) == list(current):
        return ""
    was, now = _labelled(golden), _labelled(current)
    moved = [(k, was[k], now[k]) for k in was if k in now and was[k] != now[k]]
    gone = [k for k in was if k not in now]
    fresh = [k for k in now if k not in was]

    lines = ["THE IDENTITY SURFACE MOVED."]
    if moved:
        lines += ["", f"{len(moved)} identifier(s) changed:"]
        lines += [f"  moved {label}: {old} → {new}" for label, old, new in moved]
        lines += ["", ORPHAN_WARNING + "."]
    if gone:
        lines += ["", "no longer produced:"] + [f"  gone {label}" for label in gone]
    if fresh:
        lines += ["", "newly produced:"] + [f"  added {label}" for label in fresh]
    lines += [
        "",
        "If this change is deliberate, re-baseline BY HAND after reading the "
        "diff above:",
        f"    {REBASELINE}",
    ]
    return "\n".join(lines)


