def test_identity_surface_is_unchanged(surface: list[str]) -> None:
    """The gate §7.5 assumed already existed."""
    problems = report(read_golden(), surface)
    if problems:
        pytest.fail(problems)


def test_the_surface_is_a_pure_function_of_the_source_tree(
    probe: ModuleType,
    surface: list[str],
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """From another working directory, with `MBL_STORE` unset.

    The probe's whole value is that two checkouts can be compared; a surface
    that depended on where it ran, or on a store that happened to be present,
    would make a diff mean nothing. This is also the single-specimen trap that
    already struck once in this project: every check that had ever executed the
    notebook set `MBL_STORE`, so none exercised the bare case.

    **It re-asserts the golden too, and that overlap is deliberate.** Found by
    mutation: disabling the report path in `test_identity_surface_is_unchanged`
    left the suite green when only this test still compared anything. One test
    owns the readable refusal; this one owns the hostile environment; both
    compare, so neither is the single point at which the gate can be switched
    off by editing one line.
    """
    monkeypatch.delenv("MBL_STORE", raising=False)
    monkeypatch.chdir(tmp_path)

    assert probe.surface_lines() == surface
    assert probe.surface_lines() == read_golden()


def test_the_surface_is_stable_across_two_calls(probe: ModuleType) -> None:
    """Byte-identical twice, so a diff between branches is about the branches."""
    assert probe.surface_lines() == probe.surface_lines()


